export type SiteLocale = 'fr' | 'en';

export function localeFromGeo(country?: string | null, acceptLanguage?: string | null): SiteLocale {
  if (country) return country.toUpperCase() === 'FR' ? 'fr' : 'en';
  return acceptLanguage?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

