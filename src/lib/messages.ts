export type SiteLocale = 'fr' | 'en' | 'de';

export function localeFromGeo(country?: string | null, acceptLanguage?: string | null): SiteLocale {
  if (country) {
    const countryCode = country.toUpperCase();
    if (countryCode === 'FR') return 'fr';
    if (['DE', 'AT', 'CH', 'LI', 'LU'].includes(countryCode)) return 'de';
    return 'en';
  }

  const language = acceptLanguage?.toLowerCase() ?? '';
  if (language.startsWith('fr')) return 'fr';
  if (language.startsWith('de')) return 'de';
  return 'en';
}

